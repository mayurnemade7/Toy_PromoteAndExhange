#!/usr/bin/env node
/**
 * generate-firebase-config.js
 * 
 * Reads from .env and generates firebase-config.js for local dev.
 * Run:  node generate-firebase-config.js
 * 
 * In CI/CD, secrets are injected by GitHub Actions / Vault instead.
 */
import { readFileSync, writeFileSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dir = dirname(fileURLToPath(import.meta.url));

// Load .env manually (no dotenv dependency needed)
function loadEnv(path) {
  try {
    const raw = readFileSync(path, 'utf8');
    const vars = {};
    for (const line of raw.split('\n')) {
      const trimmed = line.trim();
      if (!trimmed || trimmed.startsWith('#')) continue;
      const [key, ...rest] = trimmed.split('=');
      vars[key.trim()] = rest.join('=').trim();
    }
    return vars;
  } catch { return {}; }
}

const env = {
  ...loadEnv(resolve(__dir, '.env')),
  ...process.env   // process.env overrides .env (CI/CD injects here)
};

const required = [
  'FIREBASE_API_KEY', 'FIREBASE_AUTH_DOMAIN', 'FIREBASE_PROJECT_ID',
  'FIREBASE_STORAGE_BUCKET', 'FIREBASE_MESSAGING_SENDER_ID', 'FIREBASE_APP_ID'
];

const missing = required.filter(k => !env[k]);
if (missing.length) {
  console.error('❌ Missing env vars:', missing.join(', '));
  console.error('   Copy .env.example → .env and fill values, or set CI secrets.');
  process.exit(1);
}

const config = `// AUTO-GENERATED — DO NOT EDIT MANUALLY
// Generated by: node generate-firebase-config.js
// Source:        .env (local) or Vault/GitHub Secrets (CI)
// ⚠️  This file is gitignored — never commit it.

const firebaseConfig = {
  apiKey:            "${env.FIREBASE_API_KEY}",
  authDomain:        "${env.FIREBASE_AUTH_DOMAIN}",
  projectId:         "${env.FIREBASE_PROJECT_ID}",
  storageBucket:     "${env.FIREBASE_STORAGE_BUCKET}",
  messagingSenderId: "${env.FIREBASE_MESSAGING_SENDER_ID}",
  appId:             "${env.FIREBASE_APP_ID}"
};

export default firebaseConfig;
`;

const outPath = resolve(__dir, 'company/agile_dashboard/firebase-config.js');
writeFileSync(outPath, config, 'utf8');
console.log('✅ firebase-config.js generated at:', outPath);
